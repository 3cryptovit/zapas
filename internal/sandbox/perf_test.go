package sandbox_test

import (
	"context"
	"testing"
	"time"
)

// TestСозданиеУкладываетсяВБюджет — цель §7.1: демо создаётся не дольше
// трёх секунд.
//
// Порог мягче целевого: тест идёт в контейнере на общей с другими тестами
// базе, и ловить он должен деградацию на порядок, а не дрожание в сотни
// миллисекунд.
func TestСозданиеУкладываетсяВБюджет(t *testing.T) {
	e := setup(t)
	ctx := context.Background()

	start := time.Now()
	if _, err := e.sandbox.Create(ctx, 2024); err != nil {
		t.Fatal(err)
	}
	elapsed := time.Since(start)

	t.Logf("создание песочницы заняло %v (цель ТЗ — 3 с)", elapsed)

	// Замер на момент написания: 2,4 с в контейнере на общей базе.
	// Порог держим с запасом — тест должен ловить деградацию,
	// а не дрожание соседних тестов.
	if elapsed > 6*time.Second {
		t.Errorf("создание заняло %v при цели 3 с — что-то стало заметно медленнее", elapsed)
	}
}
