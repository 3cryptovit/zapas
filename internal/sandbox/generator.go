// demand считает спрос позиции на день (§7.2):
// базовый спрос × индекс дня недели × медленный тренд × шум,
// плюс всплеск раз в 3–4 недели.
func demand(rng *rand.Rand, spec itemSpec, dayIndex int, day clock.Day) float64 {
	v := spec.Base

	// В субботу и воскресенье поток больше.
	if day.Weekday() >= 6 {
		v *= spec.WeekendFactor
	}

	// Медленный тренд ±10% за весь период.
	trend := 1 + 0.10*(float64(dayIndex)/float64(HistoryDays)-0.5)*2
	v *= trend

	// Случайный шум.
	v *= 1 + spec.Noise*(rng.Float64()*2-1)

	// Раз в 3–4 недели мероприятие рядом: спрос вдвое выше.
	if dayIndex > 0 && dayIndex%spikePeriod(rng, dayIndex) == 0 {
		v *= 2
	}

	if v < 0 {
		return 0
	}
	return v
}

// spikePeriod — период всплесков: 21 или 28 дней, стабильно для дня.
func spikePeriod(rng *rand.Rand, dayIndex int) int {
	// Период не должен зависеть от порядка вызовов, поэтому считаем его
	// от номера дня, а не от текущего состояния генератора.
	_ = rng
	if (dayIndex/21)%2 == 0 {
		return 21
	}
	return 28
}

// writeoffRate — доля списаний от дневного расхода: 1–3% (§7.2).
func writeoffRate(rng *rand.Rand) float64 { return 0.01 + rng.Float64()*0.02 }
