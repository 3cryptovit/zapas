// Параметры сценария «Кофейня» (§7.2).
const (
	// HistoryDays — сколько дней истории видит посетитель на входе.
	HistoryDays = 90
	// MaxVirtualDays — не больше 60 виртуальных дней вперёд на песочницу (§7.5).
	MaxVirtualDays = 60
	// MaxItems и MaxMovements — потолки объёма данных (§7.5).
	MaxItems     = 200
	MaxMovements = 20000
)

// supplierSpec — поставщик из таблицы §7.2.
type supplierSpec struct {
	Name     string
	Contact  string
	LeadDays int
	// Weekdays — дни доставки в нумерации ISO: пн = 1 … вс = 7.
	Weekdays []int16
	Cutoff   string
}

// itemSpec — позиция демо-каталога.
type itemSpec struct {
	Name     string
	Unit     string
	Category string
	Supplier string
	// Base — базовый дневной спрос в базовой единице.
	Base float64
	// WeekendFactor — насколько больше расходуется в выходные.
	WeekendFactor float64
	// Noise — разброс дневного спроса.
	Noise float64
	// PurchaseUnit, UnitFactor, Pack — условия закупки.
	PurchaseUnit string
	UnitFactor   string
	Pack         string
	// Price — цена за единицу закупки.
	Price string
}

